export const BED_PAGES = TIME_PAGES.filter((p) => p.kind === 'bed');

export function slugFor(page: Pick<TimePage, 'kind' | 'time'>): string {
  const t = page.time.replace(':', '-');
  return page.kind === 'wake' ? `vo-skolko-lech-chtoby-vstat-v-${t}` : `esli-lech-v-${t}-vo-skolko-vstavat`;
}

export function pageQuestion(page: Pick<TimePage, 'kind' | 'time'>): string {
  return page.kind === 'wake'
    ? `Во сколько лечь, чтобы встать в ${page.time}`
    : `Если лечь в ${page.time}, во сколько вставать`;
}

/** Подставляет время в плейсхолдеры {t}, {c1}…{c6}, {coffee}. */
export function fillText(text: string, values: Record<string, string>): string {
  return text.replace(/\{(\w+)\}/g, (m, key: string) => {
    if (!(key in values)) throw new Error(`Нет значения для ${m} в «${text}»`);
    return values[key];
  });
}
