// Посадочные страницы двух типов:
//  wake — «Во сколько лечь, чтобы встать в HH:MM»,
//  bed  — «Если лечь в HH:MM, во сколько вставать».
//
// Тексты уникальны для каждой страницы. Время в них — плейсхолдеры, их подставляет fillText():
//  {t} — время страницы; {c1}…{c6} — вариант для 1…6 циклов
//  (wake: время отбоя, bed: время подъёма); {coffee} — за 6 часов до отбоя на 5 циклов.

export type PageKind = 'wake' | 'bed';

/** Расчётный блок страницы. Блоки чередуются, чтобы страницы не повторяли друг друга. */
